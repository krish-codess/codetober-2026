// Profiles an attempts feed the way you would profile an unfamiliar source before designing a schema around it:
// parse failures, per-field nulls / types / cardinality, value distributions, duplicates, ordering, arrival shape.
//   node loadtest/profile-attempts.mjs data/generated/attempts.ndjson > docs/data-profile.md
import { readFileSync } from 'node:fs'

const file = process.argv[2]
const lines = readFileSync(file, 'utf8').split('\n').filter((l) => l.length)
const FIELDS = ['attempt_id', 'user_id', 'event_id', 'ticket_type', 'section', 'quantity', 'client_ts']
const stat = Object.fromEntries(FIELDS.map((f) => [f, { missing: 0, nul: 0, types: {}, values: new Map() }]))
let unparseable = 0
const seen = new Map()
const ts = []
const tsFormats = { iso: 0, epoch: 0, other: 0 }

const parseTs = (v) => {
  if (typeof v === 'number') return (tsFormats.epoch++, v)
  if (typeof v === 'string' && /^\d{4}-\d\d-\d\dT.*Z$/.test(v)) return (tsFormats.iso++, Date.parse(v))
  const m = typeof v === 'string' && v.match(/^(\d\d)\/(\d\d)\/(\d{4}) (\d\d):(\d\d):(\d\d)$/)
  if (m) return (tsFormats.other++, Date.UTC(+m[3], +m[2] - 1, +m[1], +m[4], +m[5], +m[6]))
  return null
}

for (const line of lines) {
  let rec
  try {
    rec = JSON.parse(line)
  } catch {
    unparseable++
    continue
  }
  for (const f of FIELDS) {
    const st = stat[f]
    const v = rec[f]
    if (v === undefined) st.missing++
    else if (v === null) st.nul++
    else {
      st.types[typeof v] = (st.types[typeof v] ?? 0) + 1
      st.values.set(v, (st.values.get(v) ?? 0) + 1)
    }
  }
  if (rec.attempt_id) seen.set(rec.attempt_id, (seen.get(rec.attempt_id) ?? 0) + 1)
  const t = parseTs(rec.client_ts)
  if (t !== null) ts.push(t)
}

const n = lines.length
const pct = (x) => ((100 * x) / n).toFixed(2) + '%'
const top = (m, k = 8) =>
  [...m].sort((a, b) => b[1] - a[1]).slice(0, k).map(([v, c]) => `\`${JSON.stringify(v)}\` x${c}`).join(', ')
const dupIds = [...seen.values()].filter((c) => c > 1).length
let outOfOrder = 0
let maxLate = 0
let hi = -Infinity
for (const t of ts) {
  if (t < hi) {
    outOfOrder++
    maxLate = Math.max(maxLate, hi - t)
  } else hi = t
}
const sorted = [...ts].sort((a, b) => a - b)
const perSec = new Map()
for (const t of ts) perSec.set(Math.floor(t / 1000), (perSec.get(Math.floor(t / 1000)) ?? 0) + 1)
const [peakSec, peak] = [...perSec].sort((a, b) => b[1] - a[1])[0]
const q = (p) => new Date(sorted[Math.floor(p * (sorted.length - 1))]).toISOString()
const within = (s) => ts.filter((t) => t >= peakSec * 1000 && t < (peakSec + s) * 1000).length

console.log(`# Data profile: \`${file}\`

Generated by \`loadtest/profile-attempts.mjs\`. Regenerate rather than edit.

- Lines: **${n}**
- Unparseable JSON: **${unparseable}** (${pct(unparseable)})
- Distinct \`attempt_id\`: **${seen.size}**; ids appearing more than once: **${dupIds}** (${pct(dupIds)})
- Out-of-order by \`client_ts\`: **${outOfOrder}** (${pct(outOfOrder)}), worst lateness **${(maxLate / 1000).toFixed(1)} s**
- \`client_ts\` formats: ISO-8601 UTC ${tsFormats.iso}, epoch millis ${tsFormats.epoch}, \`dd/MM/yyyy HH:mm:ss\` (no zone) ${tsFormats.other}

## Fields

| field | missing | null | types | distinct | top values |
|---|---|---|---|---|---|`)
for (const f of FIELDS) {
  const st = stat[f]
  const showTop = st.values.size <= 50 ? top(st.values) : '(high cardinality)'
  const types = Object.entries(st.types).map(([t, c]) => `${t} ${c}`).join(', ')
  console.log(`| \`${f}\` | ${st.missing} | ${st.nul} | ${types} | ${st.values.size} | ${showTop} |`)
}
console.log(`
## Arrival shape

- First / median / last \`client_ts\`: ${q(0)} / ${q(0.5)} / ${q(1)}
- Peak second: **${new Date(peakSec * 1000).toISOString()}** with **${peak}** attempts
- Share of all attempts within 1 s / 5 s / 30 s of the peak second's start: ${pct(within(1))} / ${pct(within(5))} / ${pct(within(30))}
`)
